    private static final class Objective extends TwiceDifferentiableFunction {

        @Override
        public int dim() {
            return N;
        }

        @Override
        public double value(final RealVector point) {
            double value = 0.0;

            for (int k = 0; k < SPECIAL_INDEX.length; ++k) {
                value += reservoirTerm(point.getEntry(SPECIAL_INDEX[k]),
                                       SPECIAL_A[k],
                                       SPECIAL_B[k]);
            }

            for (int i = 0; i < PIPE_COEFFICIENT.length; ++i) {
                final double coefficient = PIPE_COEFFICIENT[i];
                if (coefficient != 0.0) {
                    final double xi = point.getEntry(i);
                    value += coefficient * xi * xi *
                             FastMath.pow(FastMath.abs(xi) + EPS, 0.85);
                }
            }

            for (int k = 0; k < LINEAR_COEFFICIENT.length; ++k) {
                value += LINEAR_COEFFICIENT[k] *
                         point.getEntry(190 + k);
            }

            return value;
        }

        @Override
        public RealVector gradient(final RealVector point) {
            final double[] gradient = new double[N];

            for (int k = 0; k < SPECIAL_INDEX.length; ++k) {
                final int index = SPECIAL_INDEX[k];
                final double x = point.getEntry(index);
                gradient[index] =
                        -FastMath.sqrt(FastMath.max(
                                SPECIAL_B[k] *
                                (SPECIAL_A[k] - x * x),
                                0.0));
            }

            for (int i = 0; i < PIPE_COEFFICIENT.length; ++i) {
                final double coefficient = PIPE_COEFFICIENT[i];
                if (coefficient != 0.0) {
                    final double x = point.getEntry(i);
                    final double absolute = FastMath.abs(x);
                    final double shifted = absolute + EPS;
                    final double sign = FastMath.signum(x);
                    gradient[i] =
                            coefficient *
                            (2.0 * x * FastMath.pow(shifted, 0.85) +
                             0.85 * x * x * sign *
                             FastMath.pow(shifted, -0.15));
                }
            }

            for (int k = 0; k < LINEAR_COEFFICIENT.length; ++k) {
                gradient[190 + k] = LINEAR_COEFFICIENT[k];
            }

            return new ArrayRealVector(gradient, false);
        }

        @Override
        public RealMatrix hessian(final RealVector point) {
            return null;
        }

        private static double reservoirTerm(final double x,
                                            final double a,
                                            final double b) {
            final double rootA = FastMath.sqrt(a);
            final double limited =
                    FastMath.max(-rootA, FastMath.min(x, rootA));
            final double radicand =
                    FastMath.max(b * (a - limited * limited), 0.0);
            final double ratio =
                    FastMath.max(-1.0,
                                 FastMath.min(1.0, limited / rootA));

            return -0.5 *
                   (limited * FastMath.sqrt(radicand) +
                    a * FastMath.sqrt(b) * FastMath.asin(ratio));
        }
    }

    private static final class Equalities extends EqualityConstraint {

        private static final RealMatrix JACOBIAN = buildJacobian();

        Equalities() {
            super(new ArrayRealVector(M));
        }

        @Override
        public int dim() {
            return N;
        }

        @Override
        public RealVector value(final RealVector point) {
            final double[] residual = CONSTANT.clone();

            for (int row = 0; row < M; ++row) {
                for (int k = ROW_START[row];
                     k < ROW_START[row + 1];
                     ++k) {
                    residual[row] +=
                            COEFFICIENT[k] *
                            point.getEntry(COLUMN[k]);
                }
            }

            return new ArrayRealVector(residual, false);
        }

        @Override
        public RealMatrix jacobian(final RealVector point) {
            return JACOBIAN;
        }

        private static RealMatrix buildJacobian() {
            final RealMatrix jacobian =
                    new OpenMapRealMatrix(M, N);

            for (int row = 0; row < M; ++row) {
                for (int k = ROW_START[row];
                     k < ROW_START[row + 1];
                     ++k) {
                    jacobian.setEntry(row,
                                      COLUMN[k],
                                      COEFFICIENT[k]);
                }
            }

            return jacobian;
        }
    }

