    private static final class Objective extends TwiceDifferentiableFunction {

        @Override
        public int dim() {
            return N;
        }

        @Override
        public double value(final RealVector point) {
            return 100.0 * point.getEntry(0);
        }

        @Override
        public RealVector gradient(final RealVector point) {
            final ArrayRealVector gradient = new ArrayRealVector(N);
            gradient.setEntry(0, 100.0);
            return gradient;
        }

        @Override
        public RealMatrix hessian(final RealVector point) {
            return new Array2DRowRealMatrix(N, N);
        }
    }

    private static final class Inequalities extends InequalityConstraint {

        Inequalities() {
            super(new ArrayRealVector(M));
        }

        @Override
        public int dim() {
            return N;
        }

        @Override
        public RealVector value(final RealVector point) {
            final double[] x = point.toArray();
            final double[] residual = new double[M];

            for (int row = 0; row < M; ++row) {
                double value = 0.0;
                for (int k = ROW_START[row]; k < ROW_START[row + 1]; ++k) {
                    final int i = TERM_I[k];
                    final int j = TERM_J[k];
                    final double c = TERM_COEFFICIENT[k];

                    if (i < 0) {
                        value += c;
                    } else if (j < 0) {
                        value += c * x[i];
                    } else {
                        value += c * x[i] * x[j];
                    }
                }
                residual[row] = value;
            }

            return new ArrayRealVector(residual, false);
        }

        @Override
        public RealMatrix jacobian(final RealVector point) {
            final double[] x = point.toArray();
            final RealMatrix jacobian = new Array2DRowRealMatrix(M, N);

            for (int row = 0; row < M; ++row) {
                for (int k = ROW_START[row]; k < ROW_START[row + 1]; ++k) {
                    final int i = TERM_I[k];
                    final int j = TERM_J[k];
                    final double c = TERM_COEFFICIENT[k];

                    if (i < 0) {
                        continue;
                    } else if (j < 0) {
                        jacobian.addToEntry(row, i, c);
                    } else if (i == j) {
                        jacobian.addToEntry(row, i, 2.0 * c * x[i]);
                    } else {
                        jacobian.addToEntry(row, i, c * x[j]);
                        jacobian.addToEntry(row, j, c * x[i]);
                    }
                }
            }

            return jacobian;
        }
    }

    private static double[] initialPoint() {
        final double[] start = new double[N];
        Arrays.fill(start, 1.0);
        return start;
    }

